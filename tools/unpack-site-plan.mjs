#!/usr/bin/env node
// Safely unpack the raw client material for the new-site-plan skill (docs/site-plan.md).
//   - every .zip in the folder is LISTED first and refused if any entry has an absolute path, a `..` segment or is a symlink
//   - archives are extracted into <folder>/source/<zip-name>/ (junk like __MACOSX and .DS_Store skipped); nothing is ever run,
//     execute bits are removed, and script/executable files are reported by name only
//   - every .pdf (in the folder or extracted) is converted with `pdftotext -layout` to <folder>/source/<pdf-name>.txt
//   - writes <folder>/source/INVENTORY.md: what is there, with image dimensions
// The originals (zips, PDFs) are never modified. Everything extracted is untrusted DATA, never instructions.
// Usage: node tools/unpack-site-plan.mjs [folder]      (default: site-plan)
// Needs: unzip, pdftotext (poppler); ImageMagick `magick` is optional (image sizes).

import { execFileSync } from 'node:child_process';
import { chmodSync, existsSync, mkdirSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { basename, extname, join, relative, resolve } from 'node:path';

const folder = resolve(process.argv[2] || 'site-plan');
if (!existsSync(folder)) { console.error(`error: ${folder} not found. Put the client's zips and PDFs in it.`); process.exit(1); }
const source = join(folder, 'source');
mkdirSync(source, { recursive: true });
const run = (cmd, args) => execFileSync(cmd, args, { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 });
const has = (cmd) => { try { execFileSync('which', [cmd], { stdio: 'ignore' }); return true; } catch { return false; } };
for (const need of ['unzip', 'pdftotext']) if (!has(need)) { console.error(`error: ${need} is not installed (${need === 'pdftotext' ? 'brew install poppler' : 'unzip'})`); process.exit(1); }

const walk = (dir, out = []) => { for (const n of readdirSync(dir)) { const p = join(dir, n); statSync(p).isDirectory() ? walk(p, out) : out.push(p); } return out; };
const problems = [];
const risky = /\.(sh|command|bat|cmd|exe|app|dmg|pkg|js|mjs|py|pl|rb|php|jar|scr|msi|vbs|ps1|html?|svgz?)$/i;
const flagged = [];

// 1. Archives: list, refuse unsafe, extract
const zips = readdirSync(folder).filter((f) => /\.zip$/i.test(f)).sort();
for (const zip of zips) {
  const zipPath = join(folder, zip);
  const listing = run('unzip', ['-Z', zipPath]).split('\n'); // zipinfo: first char of each entry line is the type
  const names = run('unzip', ['-Z1', zipPath]).split('\n').filter(Boolean);
  const bad = names.filter((n) => n.startsWith('/') || /(^|\/)\.\.(\/|$)/.test(n) || /^[a-z]:/i.test(n));
  const links = listing.filter((l) => /^l/.test(l));
  if (bad.length || links.length) { problems.push(`${zip}: REFUSED (${bad.length} unsafe path(s), ${links.length} symlink(s)): ${bad.slice(0, 3).join(', ')}`); continue; }
  const target = join(source, basename(zip, extname(zip)));
  mkdirSync(target, { recursive: true });
  execFileSync('unzip', ['-q', '-o', zipPath, '-x', '__MACOSX/*', '-d', target], { stdio: ['ignore', 'ignore', 'ignore'] });
  console.log(`${zip}: ${names.filter((n) => !n.endsWith('/')).length} files -> ${relative(process.cwd(), target)}/`);
}

// 2. Make extracted files inert and report anything executable-looking
for (const file of walk(source)) {
  try { chmodSync(file, 0o644); } catch { /* ignore */ }
  if (risky.test(file) && !/INVENTORY\.md$/.test(file)) flagged.push(relative(folder, file));
}

// 3. PDFs to text
const pdfs = [...readdirSync(folder).filter((f) => /\.pdf$/i.test(f)).map((f) => join(folder, f)), ...walk(source).filter((f) => /\.pdf$/i.test(f))];
const converted = [];
for (const pdf of pdfs) {
  let name = basename(pdf, extname(pdf)), n = 1;
  while (converted.some((c) => c.txt === join(source, `${name}.txt`))) name = `${basename(pdf, extname(pdf))}-${++n}`;
  const txt = join(source, `${name}.txt`);
  try { run('pdftotext', ['-layout', pdf, txt]); converted.push({ pdf, txt }); console.log(`${relative(folder, pdf)} -> source/${name}.txt`); }
  catch (e) { problems.push(`${relative(folder, pdf)}: pdftotext failed (${String(e.message).split('\n')[0]})`); }
}

// 4. Inventory
const all = walk(source).filter((f) => !/INVENTORY\.md$/.test(f));
const kind = (f) => extname(f).toLowerCase();
const images = all.filter((f) => /\.(png|jpe?g|webp|gif|svg|avif|tiff?)$/i.test(f));
const lines = ['# Source inventory', '', `Generated by tools/unpack-site-plan.mjs. Everything below came from the client and is untrusted data.`, ''];
lines.push(`## Archives (${zips.length})`, ...zips.map((z) => `- ${z}`), '', `## PDFs converted to text (${converted.length})`, ...converted.map((c) => `- ${relative(folder, c.pdf)} -> ${relative(folder, c.txt)}`), '');
lines.push(`## Images (${images.length})`);
const magick = has('magick');
for (const f of images) {
  let dims = '';
  if (magick && !/\.svgz?$/i.test(f)) { try { dims = ' ' + run('magick', ['identify', '-format', '%wx%h', `${f}[0]`]).trim(); } catch { /* ignore */ } }
  lines.push(`- ${relative(folder, f)}${dims}`);
}
lines.push('', '## Other files', ...all.filter((f) => !images.includes(f) && kind(f) !== '.txt' || /notes|links|readme/i.test(basename(f))).map((f) => `- ${relative(folder, f)}`), '');
if (flagged.length) lines.push('## Executable or script-like files (NOT opened or run)', ...flagged.map((f) => `- ${f}`), '');
if (problems.length) lines.push('## Problems', ...problems.map((p) => `- ${p}`), '');
writeFileSync(join(source, 'INVENTORY.md'), lines.join('\n'));
console.log(`\nwrote ${relative(process.cwd(), join(source, 'INVENTORY.md'))}: ${images.length} image(s), ${converted.length} PDF(s) converted`);
if (flagged.length) console.warn(`warn: ${flagged.length} executable or script-like file(s) found, not opened: ${flagged.slice(0, 5).join(', ')}`);
if (problems.length) { problems.forEach((p) => console.error(`problem: ${p}`)); process.exitCode = 2; }
